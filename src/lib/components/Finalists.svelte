<section class="finalists" id="finalists">
	<div class="wrap">
		<div class="section-head">
			<div>
				<p class="eyebrow">Where to rent the villa</p>
				<h2>The right town matters as much as the island.</h2>
			</div>
			<p>
				These are search zones, not availability claims. With flexible dates, first choose the
				island and base, then verify exact totals, pool heat, child safety and cancellation terms
				for the selected eight- or nine-night window.
			</p>
		</div>

		<article class="island-story">
			<div class="story-top">
				<div>
					<p class="eyebrow">Best overall · FUE-01</p>
					<h3>North Fuerteventura</h3>
					<p>
						The north works as one surf ecosystem. Schools based in Corralejo and El Cotillo drive
						students to the safest break for the day, while Lajares and Villaverde hold many of the
						larger pool villas. Corralejo dunes and El Cotillo lagoons cover the beach days.
					</p>
				</div>
				<div class="story-score"><b>90</b><span>weighted activity score / 100</span></div>
			</div>
			<div class="town-grid">
				<div class="town recommended">
					<span class="label">Best group-villa base</span>
					<h4>Lajares</h4>
					<p>
						Large villas, quiet evenings, cafés and a central position: roughly 10–15 minutes to
						both Corralejo and El Cotillo surf zones. No walkable beach.
					</p>
				</div>
				<div class="town">
					<span class="label">Best all-round services</span>
					<h4>Corralejo</h4>
					<p>
						Deepest school/rental choice, restaurants, groceries, dunes and Lobos ferries. Look on
						the quieter western and southern edges for 4–5 bedroom homes.
					</p>
				</div>
				<div class="town">
					<span class="label">Best beach-town feel</span>
					<h4>El Cotillo</h4>
					<p>
						Calm white-sand lagoons north of town and west-coast surf to the south. Fewer truly
						large villas, so book early when dates are fixed.
					</p>
				</div>
				<div class="town">
					<span class="label">Best space and value</span>
					<h4>Villaverde</h4>
					<p>
						Detached villas and views, around 15 minutes from Corralejo and Lajares. Good budget
						fallback; every outing requires a car.
					</p>
				</div>
			</div>
			<div class="callout-grid">
				<div class="callout good">
					<h4>Why it wins</h4>
					<p>
						Surf schools can move the group between beaches; non-surfers still get white sand,
						dunes, sheltered lagoons, Lobos and easy family days.
					</p>
				</div>
				<div class="callout warning">
					<h4>What could change the decision</h4>
					<p>
						Fuerteventura is the most arid and can feel windy. Its hiking is scenic but less varied
						than Tenerife, Gran Canaria or Lanzarote.
					</p>
				</div>
			</div>
		</article>

		<article class="island-story">
			<div class="story-top">
				<div>
					<p class="eyebrow">Best surf + hiking blend · ACE-01</p>
					<h3>North Lanzarote</h3>
					<p>
						Famara is the cleanest learner proposition in the archipelago: one enormous sandy
						training beach, many schools and an unforgettable cliff backdrop. The island's volcanic
						attractions are compact and exceptional. The compromise is accommodation: Famara itself
						has fewer ten-person villas.
					</p>
				</div>
				<div class="story-score"><b>89</b><span>weighted activity score / 100</span></div>
			</div>
			<div class="town-grid">
				<div class="town recommended">
					<span class="label">Best balanced base</span>
					<h4>Soo / Muñique</h4>
					<p>
						Rural villas with more space and pools, normally 8–15 minutes from Famara. Little
						nightlife, but ideal for a large group with cars.
					</p>
				</div>
				<div class="town">
					<span class="label">Best walk-to-surf</span>
					<h4>Caleta de Famara</h4>
					<p>
						Surf village beside the 6 km beach. Authentic and convenient, but exposed to wind and
						the large-villa inventory is thinner.
					</p>
				</div>
				<div class="town">
					<span class="label">Best volcanic hub</span>
					<h4>Tinajo / La Vegueta</h4>
					<p>
						Good rural homes, 15–25 minutes to Famara and closer to Caldera Blanca and Timanfaya.
						Beach trips always involve driving.
					</p>
				</div>
				<div class="town">
					<span class="label">Best family services</span>
					<h4>Costa Teguise</h4>
					<p>
						More villa stock, playgrounds and sandy coves, about 25–30 minutes from Famara. Less
						atmospheric than the rural north.
					</p>
				</div>
			</div>
			<div class="callout-grid">
				<div class="callout good">
					<h4>Why it nearly wins</h4>
					<p>
						Famara puts beginner and intermediate coaching on sand, while Caldera Blanca, Timanfaya,
						Jameos del Agua and La Graciosa fill every flat day.
					</p>
				</div>
				<div class="callout warning">
					<h4>Watch-outs</h4>
					<p>
						Famara is exposed, currents matter, and a remote villa can make every grocery run and
						beach transfer a car operation.
					</p>
				</div>
			</div>
		</article>

		<article class="island-story">
			<div class="story-top">
				<div>
					<p class="eyebrow">Best urban surf · LPA-01</p>
					<h3>Las Palmas, Gran Canaria</h3>
					<p>
						La Cícer combines a sandy beach break, many schools and city life better than anywhere
						else. The flaw is structural: the best surf base is apartment-heavy, while large sunny
						villas cluster in the south, 40–50 minutes away.
					</p>
				</div>
				<div class="story-score"><b>88</b><span>weighted activity score / 100</span></div>
			</div>
			<div class="town-grid">
				<div class="town recommended">
					<span class="label">Best surf-first base</span>
					<h4>Las Palmas west</h4>
					<p>
						Search Guanarteme and the inland edge of La Cícer for a rare whole house. Walkable surf
						and beach; accept urban density and limited pools.
					</p>
				</div>
				<div class="town">
					<span class="label">Best house compromise</span>
					<h4>Arucas / Bañaderos</h4>
					<p>
						Larger homes 15–25 minutes from La Cícer and north-coast breaks. Greener and cooler,
						with fewer classic resort beaches.
					</p>
				</div>
				<div class="town">
					<span class="label">Best hiking access</span>
					<h4>Santa Brígida / Tafira</h4>
					<p>
						Villas and gardens, 20–30 minutes to surf and good access inland. Cooler at elevation;
						no beach-town feeling.
					</p>
				</div>
				<div class="town">
					<span class="label">Best family resort</span>
					<h4>Maspalomas / Meloneras</h4>
					<p>
						Excellent villas, dunes and family weather, but daily surf transfers to La Cícer
						undermine a surf-first trip.
					</p>
				</div>
			</div>
		</article>

		<article class="island-story">
			<div class="story-top">
				<div>
					<p class="eyebrow">Best family depth · TFS-01</p>
					<h3>South Tenerife</h3>
					<p>
						Tenerife is the most complete family island and the strongest hiker's island. Its
						south-coast surf, however, is dominated by volcanic reef. That makes it excellent for
						improving surfers with guidance, but less aligned with the request for sandy
						beginner–intermediate breaks.
					</p>
				</div>
				<div class="story-score"><b>84</b><span>weighted activity score / 100</span></div>
			</div>
			<div class="town-grid">
				<div class="town recommended">
					<span class="label">Best villa value</span>
					<h4>Callao Salvaje / Playa Paraíso</h4>
					<p>
						Large villa market, quieter streets and roughly 15–25 minutes to Las Américas surf.
						Sandy family beaches nearby, but not surf beaches.
					</p>
				</div>
				<div class="town">
					<span class="label">Best convenience</span>
					<h4>Costa Adeje</h4>
					<p>
						Family beaches, restaurants, Siam Park and short drives to surf. Large detached villas
						can be expensive inside the resort core.
					</p>
				</div>
				<div class="town">
					<span class="label">Best quiet compromise</span>
					<h4>Palm-Mar</h4>
					<p>
						Villas and a calm residential feel, roughly 15–20 minutes to Las Américas. The local
						coast is rocky, so sand requires a drive.
					</p>
				</div>
				<div class="town">
					<span class="label">Best sandy surf identity</span>
					<h4>El Médano</h4>
					<p>
						Natural sand and water-sport culture, but winter board surfing is less reliable and wind
						can dominate. Better for wind/kite than this brief.
					</p>
				</div>
			</div>
		</article>
	</div>
</section>

